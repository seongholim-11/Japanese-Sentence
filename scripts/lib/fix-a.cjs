const fs = require('fs');
const J = 'D:/personal_project/Japanese-Sentence/src/data/content/json/';
const rd = (f) => JSON.parse(fs.readFileSync(J + f, 'utf8'));
const wr = (f, d) => {
  if (Array.isArray(d)) fs.writeFileSync(J + f, '[\n' + d.map((r) => JSON.stringify(r)).join(',\n') + '\n]\n');
  else if (d.rows) fs.writeFileSync(J + f, '{"level":' + JSON.stringify(d.level) + ',"rows":[\n' + d.rows.map((r) => JSON.stringify(r)).join(',\n') + '\n]}\n');
};
const miss = [];
function upd(f, pred, fn, label) {
  const d = rd(f);
  const rows = Array.isArray(d) ? d : d.rows;
  let n = 0;
  for (const r of rows) if (pred(r)) { fn(r); n++; }
  if (!n) miss.push(f + ':' + label);
  wr(f, d);
}
