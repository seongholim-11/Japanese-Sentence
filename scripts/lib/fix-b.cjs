const rd = (f) => JSON.parse(fs.readFileSync(J + f, 'utf8'));
const wr = (f, d) => fs.writeFileSync(J + f, '[\n' + d.map((r) => JSON.stringify(r)).join(',\n') + '\n]\n');
const miss = [];
function dlg(file, id, fn) {
  const d = rd(file);
  const x = d.find((e) => e.id === id);
  if (!x) { miss.push(file + ':' + id); return; }
  fn(x);
  wr(file, d);
}
